test('mobile layout, immediate navigation preserves draft, malformed backup rejected',async({page})=>{
  await page.setViewportSize({width:390,height:844});
  await page.goto('/');
  await page.screenshot({path:'.preview/mobile.png',fullPage:true});
  await page.getByRole('button',{name:'New project',exact:true}).click();
  await page.getByLabel('Working title',{exact:true}).fill('   ');
  await page.getByRole('button',{name:'Create project'}).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.getByLabel('Working title',{exact:true}).fill('Mobile project');
  await page.getByRole('button',{name:'Create project'}).click();
  await page.getByRole('navigation',{name:'Project stages'}).getByRole('button',{name:'Draft',exact:false}).click();
  await page.getByLabel('Working draft',{exact:true}).fill('Unsaved version, retained working text.');
  await page.getByRole('navigation',{name:'Main navigation'}).getByRole('button',{name:'Workbench'}).click();
  await page.locator('.project-row').filter({hasText:'Mobile project'}).click();
  await page.getByRole('navigation',{name:'Project stages'}).getByRole('button',{name:'Draft',exact:false}).click();
  await expect(page.getByLabel('Working draft',{exact:true})).toHaveValue('Unsaved version, retained working text.');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.getByRole('navigation',{name:'Main navigation'}).getByRole('button',{name:'Settings'}).click();
  await page.locator('input[type=file]').setInputFiles({name:'broken.json',mimeType:'application/json',buffer:Buffer.from('{"schema":1,"projects":[]}')});
  await expect(page.getByRole('status')).toContainText('not a valid LexRadar backup');
  await expect(page.getByRole('dialog')).toHaveCount(0);
});
