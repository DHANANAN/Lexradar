import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';

test('complete research workflow, exact versions, tasks, links, and backup restore', async ({ page }) => {
  const errors:string[]=[]; page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Research workbench'})).toBeVisible();
  await page.screenshot({path:'.preview/workbench.png',fullPage:true});
  await page.getByRole('button',{name:'New project',exact:true}).click();
  await page.getByLabel('Working title',{exact:true}).fill('Access to public legal information');
  await page.getByLabel('Research question',{exact:true}).fill('How can public judgments become more accessible?');
  await page.getByLabel('Target publisher',{exact:true}).selectOption('slr');
  await page.getByRole('button',{name:'Create project'}).click();
  await page.getByRole('navigation',{name:'Project stages'}).getByRole('button',{name:'Research',exact:false}).click();
  await page.getByLabel('Source title').fill('Primary judgment');
  await page.getByLabel('Source URL').fill('https://example.com/judgment');
  await page.getByLabel('Pinpoint / evidence note').fill('Check paragraph 12');
  await page.getByRole('button',{name:'Add source',exact:true}).click();
  await page.getByLabel('Primary judgment',{exact:true}).check();
  await expect(page.getByText('Open Aura writing studio',{exact:false})).toBeVisible();
  await page.getByRole('navigation',{name:'Project stages'}).getByRole('button',{name:'Draft',exact:false}).click();
  await expect(page.getByRole('button',{name:'Download draft'})).toBeVisible();
  await page.getByLabel('Working draft',{exact:true}).fill('This manuscript examines public access to judgments. The author reviews primary materials and proposes an accessible archive.');
  await page.getByLabel('Version label').fill('First manuscript');
  await page.getByRole('button',{name:'Save version',exact:true}).click();
  await expect(page.getByText('Version saved: First manuscript')).toBeVisible();
  await page.locator('input[type=file]').setInputFiles({name:'revised.txt',mimeType:'text/plain',buffer:Buffer.from('Revised manuscript with checked references.')});
  await expect(page.getByText('Document saved: revised.txt')).toBeVisible();
  await page.getByRole('button',{name:'Add task',exact:true}).click();
  await page.getByLabel('Task',{exact:true}).fill('Follow up with the editor');
  await page.getByLabel('Due date').fill('2026-12-01');
  await page.getByRole('dialog').getByRole('button',{name:'Add task',exact:true}).click();
  await page.getByRole('navigation',{name:'Project stages'}).getByRole('button',{name:'Review',exact:false}).click();
  for(const box of await page.locator('.review-checks input').all())await box.check();
  await page.getByRole('navigation',{name:'Project stages'}).getByRole('button',{name:'Submit',exact:false}).click();
  await page.getByRole('button',{name:'Log submission',exact:true}).click();
  await page.getByLabel('Exact version sent').selectOption({label:'First manuscript'});
  await page.getByRole('button',{name:'Save submission record'}).click();
  await page.getByLabel('Editorial status').selectOption('Published');
  await page.getByLabel('Published article URL').fill('https://example.com/published');
  await page.getByRole('button',{name:'Save update'}).click();
  await expect(page.getByRole('link',{name:'Open publication'})).toHaveAttribute('href','https://example.com/published');
  await page.screenshot({path:'.preview/project.png',fullPage:true});
  await expect(page.getByText('Saved on this browser',{exact:true})).toBeVisible();
  await page.reload();
  await page.locator('.project-row').filter({hasText:'Access to public legal information'}).click();
  await expect(page.getByLabel('Editorial status')).toHaveValue('Published');
  await expect(page.locator('.tree-item').filter({has:page.getByRole('button',{name:/First manuscript/})}).getByText('Socio-Legal Review',{exact:true})).toBeVisible();
  await page.getByRole('navigation',{name:'Main navigation'}).getByRole('button',{name:'Settings'}).click();
  const dl=page.waitForEvent('download');await page.getByRole('button',{name:'Export full backup'}).click();
  const path=await (await dl).path();expect(path).toBeTruthy();
  await page.locator('input[type=file]').setInputFiles(path!);
  await expect(page.getByRole('heading',{name:'Restore this workspace?'})).toBeVisible();
  await page.getByRole('dialog').getByRole('button',{name:'Restore backup',exact:true}).click();
  await page.getByRole('navigation',{name:'Main navigation'}).getByRole('button',{name:'Workbench'}).click();
  await page.locator('.project-row').filter({hasText:'Access to public legal information'}).click();
  await page.getByRole('button',{name:/v2 revised.txt/}).click();
  const fileDownload=page.waitForEvent('download');
  await page.getByRole('button',{name:'Download version',exact:true}).click();
  const restoredPath=await(await fileDownload).path();
  expect(await readFile(restoredPath!,'utf8')).toBe('Revised manuscript with checked references.');
  await page.getByRole('button',{name:'Close dialog',exact:true}).click();
  await page.getByRole('navigation',{name:'Main navigation'}).getByRole('button',{name:'Tasks'}).click();
  await expect(page.getByText('Follow up with the editor',{exact:true})).toBeVisible();
  expect(errors).toEqual([]);
});

